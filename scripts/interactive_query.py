def main():
    console.print("\n[bold cyan]DATA PLATFORM KNOWLEDGE GRAPH[/bold cyan]  [dim]Interactive Query Interface[/dim]")
    console.print("[dim]Initializing knowledge graph...[/dim]\n")

    kg, vectorDb = loadKnowledgeGraph()
    console.print("[bold green]Knowledge graph loaded.[/bold green] Type [cyan]/help[/cyan] for commands or ask a question.\n")

    console.print("[bold white]Example questions you can ask:[/bold white]")
    for q in EXAMPLE_QUESTIONS:
        console.print(f"  [dim]-[/dim] [cyan]{q}[/cyan]")
    console.print()

    queryEngine = NaturalLanguageQueryEngine()
    handler = CommandHandler(kg, vectorDb, queryEngine)

    while True:
        try:
            userInput = input("Your question: ").strip()
            if not handler.handle(userInput):
                break
        except KeyboardInterrupt:
            console.print("\n[dim]Goodbye![/dim]")
            break
        except Exception as e:
            console.print(f"\n[red]Error:[/red] {e}")


if __name__ == "__main__":
    main()
