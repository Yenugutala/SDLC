def columnImpactAnalysis(kg: KnowledgeGraph, columnId: str) -> None:
    """
    SDLC Query: "Which dashboards break if column X changes?"

    Traversal: Column <--[READS_FROM]-- PowerBIKPI <--[CONTAINS]-- PowerBIDashboard
    """
    printHeader(f"SDLC IMPACT: Column Change → '{columnId}'")

    if columnId not in kg.graph.nodes:
        matches = [
            nId for nId, data in kg.graph.nodes(data=True)
            if data.get('type') == 'Column'
            and columnId.lower() in (data.get('name', '') + nId).lower()
        ]
        if not matches:
            print(f"\n  Column '{columnId}' not found in graph.")
            print("  Tip: Use the column ID (e.g. col_rn_kpi_value) or part of its name.")
            return
        columnId = matches[0]

    colData = kg.graph.nodes[columnId]
    print(f"\n  Column: {colData.get('name', columnId)} (ID: {columnId})")
    print(f"  Type: {colData.get('dataType', 'N/A')} | PII: {colData.get('isPii', False)}")
    print(f"  Description: {colData.get('description', 'N/A')}\n")

    affectedKPIs = [
        sourceId for sourceId in kg.graph.predecessors(columnId)
        if kg.graph.nodes[sourceId].get('type') == 'PowerBIKPI'
        and kg.graph.get_edge_data(sourceId, columnId, {}).get('relation') == 'READS_FROM'
    ]

    definingEntries = [
        sourceId for sourceId in kg.graph.predecessors(columnId)
        if kg.graph.nodes[sourceId].get('type') == 'DataDictionaryEntry'
    ]

    if not affectedKPIs and not definingEntries:
        print("  No Power BI KPIs directly read this column.")
        return

    print("  IMPACT CHAIN:\n")

    if affectedKPIs:
        print(f"  [{len(affectedKPIs)}] Power BI KPI(s) that directly read this column:")
        affectedDashboards = set()

        for kpiId in affectedKPIs:
            kpiData = kg.graph.nodes[kpiId]
            print(f"\n    ● KPI: {kpiData.get('name', kpiId)} (ID: {kpiId})")
            print(f"      Calculation: {kpiData.get('calculation', 'N/A')}")

            dashboards = [
                sourceId for sourceId in kg.graph.predecessors(kpiId)
                if kg.graph.nodes[sourceId].get('type') == 'PowerBIDashboard'
            ]
            for dashId in dashboards:
                affectedDashboards.add(dashId)
                dashData = kg.graph.nodes[dashId]
                print(f"      → BREAKS Dashboard: {dashData.get('name', dashId)} (ID: {dashId})")
                print(f"        Workspace: {dashData.get('workspace', 'N/A')} | Owner: {dashData.get('owner', 'N/A')}")

        print(f"\n  SUMMARY: {len(affectedDashboards)} dashboard(s) at risk if '{columnId}' is renamed/removed.")

    if definingEntries:
        print("\n  Data Dictionary terms that define this column:")
        for entryId in definingEntries:
            entryData = kg.graph.nodes[entryId]
            print(f"    ● Term: {entryData.get('term', entryId)} — {entryData.get('definition', '')[:80]}...")


def pipelineDependencyAnalysis(kg: KnowledgeGraph, pipelineId: str) -> None:
    """
    SDLC Query: "Which KPIs depend on pipeline X?"

    Traversal: Pipeline --[PRODUCES]--> Table <--[READS_FROM]-- KPI <--[CONTAINS]-- Dashboard
    """
    printHeader(f"SDLC IMPACT: Pipeline Dependencies → '{pipelineId}'")

    if pipelineId not in kg.graph.nodes:
        matches = [
            nId for nId, data in kg.graph.nodes(data=True)
            if data.get('type') == 'Pipeline'
            and pipelineId.lower() in (data.get('name', '') + nId).lower()
        ]
        if not matches:
            print(f"\n  Pipeline '{pipelineId}' not found in graph.")
            return
        pipelineId = matches[0]

    pipelineData = kg.graph.nodes[pipelineId]
    print(f"\n  Pipeline: {pipelineData.get('name', pipelineId)} (ID: {pipelineId})")
    print(f"  Layer: {pipelineData.get('layer', 'N/A')} | Schedule: {pipelineData.get('schedule', 'N/A')}\n")

    producedTables = [
        targetId for targetId in kg.graph.successors(pipelineId)
        if kg.graph.nodes[targetId].get('type') == 'Table'
        and kg.graph.get_edge_data(pipelineId, targetId, {}).get('relation') == 'PRODUCES'
    ]

    if not producedTables:
        print("  This pipeline does not directly produce any tables in the graph.")
        return

    print("  Tables produced by this pipeline:")
    allAffectedKPIs = {}
    allAffectedDashboards = set()

    for tableId in producedTables:
        tableData = kg.graph.nodes[tableId]
        print(f"\n    ● Table: [{tableData.get('layer', tableData.get('schema', ''))}] {tableData.get('name', tableId)} (ID: {tableId})")

        kpisFromTable = [
            sourceId for sourceId in kg.graph.predecessors(tableId)
            if kg.graph.nodes[sourceId].get('type') == 'PowerBIKPI'
            and kg.graph.get_edge_data(sourceId, tableId, {}).get('relation') == 'READS_FROM'
        ]

        if not kpisFromTable:
            print("      No KPIs directly read from this table.")
            continue

        for kpiId in kpisFromTable:
            allAffectedKPIs[kpiId] = kg.graph.nodes[kpiId]
            kpiData = kg.graph.nodes[kpiId]
            print(f"      → KPI depends on this table: {kpiData.get('name', kpiId)} (ID: {kpiId})")

            dashboards = [
                srcId for srcId in kg.graph.predecessors(kpiId)
                if kg.graph.nodes[srcId].get('type') == 'PowerBIDashboard'
            ]
            for dashId in dashboards:
                allAffectedDashboards.add(dashId)
                dashData = kg.graph.nodes[dashId]
                print(f"         → Dashboard: {dashData.get('name', dashId)}")

    print(f"\n  SUMMARY: {len(allAffectedKPIs)} KPI(s) and {len(allAffectedDashboards)} dashboard(s) depend on this pipeline.")
    if allAffectedKPIs:
        print(f"  KPIs at risk: {', '.join(d.get('name', k) for k, d in allAffectedKPIs.items())}")


def whoChangedTable(kg: KnowledgeGraph, tableId: str) -> None:
    """
    SDLC Query: "Which Jira ticket modified dataset X?"

    Traversal: JiraTicket --[MODIFIED]--> Table
    """
    printHeader(f"SDLC AUDIT: Who Changed → '{tableId}'")

    if tableId not in kg.graph.nodes:
        matches = [
            nId for nId, data in kg.graph.nodes(data=True)
            if data.get('type') == 'Table'
            and tableId.lower() in (data.get('name', '') + nId).lower()
        ]
        if not matches:
            print(f"\n  Table '{tableId}' not found in graph.")
            return
        tableId = matches[0]

    tableData = kg.graph.nodes[tableId]
    print(f"\n  Table: [{tableData.get('layer', tableData.get('schema', ''))}] {tableData.get('name', tableId)} (ID: {tableId})")
    print(f"  Description: {tableData.get('description', 'N/A')}\n")

    modifyingTickets = [
        sourceId for sourceId in kg.graph.predecessors(tableId)
        if kg.graph.nodes[sourceId].get('type') == 'JiraTicket'
        and kg.graph.get_edge_data(sourceId, tableId, {}).get('relation') == 'MODIFIED'
    ]

    if not modifyingTickets:
        print("  No Jira tickets recorded as modifying this table.")
        return

    print(f"  [{len(modifyingTickets)}] Jira ticket(s) that modified this table:\n")
    for jiraId in modifyingTickets:
        jiraData = kg.graph.nodes[jiraId]
        statusIcon = "✓" if jiraData.get('status') == 'Done' else ("~" if jiraData.get('status') == 'In Progress' else "○")
        print(f"    [{statusIcon}] {jiraId}: {jiraData.get('summary', 'N/A')}")
        print(f"        Status: {jiraData.get('status')} | Priority: {jiraData.get('priority')} | Assignee: {jiraData.get('assignee')}")

        referencedConf = [
            targetId for targetId in kg.graph.successors(jiraId)
            if kg.graph.nodes[targetId].get('type') == 'ConfluencePage'
        ]
        if referencedConf:
            for confId in referencedConf:
                confData = kg.graph.nodes[confId]
                print(f"        Docs: [{confData.get('space')}] {confData.get('title', confId)}")
        print()


