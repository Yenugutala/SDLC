"""
Interactive Natural Language Query Interface for Data Platform Knowledge Graph.

HOW QUERYING WORKS — TWO PARALLEL TRACKS:
==========================================

TRACK 1 — Pure Graph Traversal (slash commands: /sdlc, /impact, /depends, /whochanged)
  No LLM involved. Pure Python functions that walk the NetworkX directed graph
  by following specific relationship edges. Deterministic and fast.

  Example flow for /impact col_rn_kpi_value:
    1. Find node col_rn_kpi_value in the graph
    2. Find all predecessors with edge relation = READS_FROM  → gets KPI nodes
    3. For each KPI, find predecessors with type = PowerBIDashboard → gets Dashboards
    4. Print the chain: Column → KPI → Dashboard

TRACK 2 — RAG + LLM via OpenRouter (free-text natural language questions)
  No graph queries are generated by the LLM. Instead, this uses RAG:

  Step 1 — Vector Search (ChromaDB + sentence-transformers):
    The user's question is converted to an embedding and compared against
    all node embeddings stored in ChromaDB. Top 8 similar nodes are returned.

  Step 2 — Context Building (NetworkX graph):
    For each matched node, we fetch its properties AND its graph edges
    (neighbours, incoming/outgoing relationships) from NetworkX.
    This builds a rich text context string that includes the graph structure.

  Step 3 — LLM (OpenRouter → gpt-4o-mini):
    The context string + user question is sent to the LLM.
    The LLM reads the text and answers in English.
    It does NOT generate graph queries — it reads pre-fetched graph data.

Run:
    python scripts/interactive_query.py
"""

